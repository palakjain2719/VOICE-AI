import { SEED_ARTICLES } from "./seed";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** Version-1 approved knowledge as SQL. Business knowledge only — never call or lead data. */
export function buildKnowledgeSeedSql(): string {
  // Three plain statements per article: a data-modifying CTE can't update a row it inserted
  // in the same statement, so the publish step must run separately.
  const rows = SEED_ARTICLES.map((a) => {
    const kw = `array[${a.keywords.map(q).join(", ")}]::text[]`;
    return `insert into knowledge_articles (slug, category, title, audience, keywords, status)
values (${q(a.slug)}, ${q(a.category)}, ${q(a.title)}, 'customer', ${kw}, 'published')
on conflict (slug) do nothing;
insert into knowledge_versions (article_id, version, spoken_answer, status, source_reference, approved_at, published_at)
select id, 1, ${q(a.spokenAnswer)}, 'published', ${q(a.source)}, now(), now() from knowledge_articles where slug = ${q(a.slug)}
on conflict (article_id, version) do nothing;
update knowledge_articles k set published_version_id = v.id
from knowledge_versions v where v.article_id = k.id and v.version = 1 and k.slug = ${q(a.slug)} and k.published_version_id is null;`;
  });
  return `-- GENERATED by scripts/generate-knowledge-seed.ts from src/domain/knowledge/seed.ts. Do not edit by hand.
-- Approved runtime knowledge v1 (from services.md, qualified.md and the pricing.md deflection).
-- Contains no numbers from the internal pricing guide.
set search_path = aangan, public, extensions;

${rows.join("\n\n")}
`;
}
